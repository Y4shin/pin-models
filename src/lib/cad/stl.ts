import type { Shape3D } from "replicad";

export interface StlFile {
  filename: string;
  data: ArrayBuffer;
}

export interface ColoredShape {
  id: string;
  color: string;
  shape: Shape3D;
}

export interface ColorGroup<T> {
  color: string;
  parts: T[];
}

/** Groups parts by their color assignment, preserving first-seen color order. */
export function groupPartsByColor<T extends { color: string }>(parts: T[]): ColorGroup<T>[] {
  const groups: ColorGroup<T>[] = [];
  const byColor = new Map<string, ColorGroup<T>>();

  for (const part of parts) {
    let group = byColor.get(part.color);
    if (!group) {
      group = { color: part.color, parts: [] };
      byColor.set(part.color, group);
      groups.push(group);
    }
    group.parts.push(part);
  }

  return groups;
}

export function slugify(value: string): string {
  const slug = value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "part";
}

/** Stable, collision-free STL filenames derived from the model name and colors. */
export function stlFilenames(modelName: string, colors: string[]): string[] {
  const modelSlug = slugify(modelName);
  const used = new Set<string>();

  return colors.map((color) => {
    const base = `${modelSlug}-${slugify(color)}`;
    let name = `${base}.stl`;
    let suffix = 2;
    while (used.has(name)) {
      name = `${base}-${suffix}.stl`;
      suffix += 1;
    }
    used.add(name);
    return name;
  });
}

function triangleCount(buffer: ArrayBuffer): number {
  if (buffer.byteLength < 84) {
    throw new Error("Invalid binary STL: file is too short.");
  }
  const count = new DataView(buffer).getUint32(80, true);
  if (buffer.byteLength !== 84 + count * 50) {
    throw new Error("Invalid binary STL: unexpected file length.");
  }
  return count;
}

/**
 * Concatenates binary STL files into one STL. STL supports multiple disconnected
 * shells, so this groups several solids into one file without a boolean fuse.
 */
export function combineBinaryStl(buffers: ArrayBuffer[]): ArrayBuffer {
  const counts = buffers.map(triangleCount);
  const total = counts.reduce((sum, count) => sum + count, 0);

  const result = new ArrayBuffer(84 + total * 50);
  const bytes = new Uint8Array(result);
  const view = new DataView(result);

  const header = new TextEncoder().encode("Combined STL generated by pin-models-configurator");
  bytes.set(header.subarray(0, 80), 0);
  view.setUint32(80, total, true);

  let offset = 84;
  for (const buffer of buffers) {
    const body = new Uint8Array(buffer, 84);
    bytes.set(body, offset);
    offset += body.byteLength;
  }

  return result;
}

/**
 * Builds one binary STL per color group from the actual CAD solids. Groups with
 * multiple parts (for example all black seeds) are combined into a single STL
 * with disconnected shells, preserving the shared coordinate system.
 */
export async function buildStlExport(
  modelName: string,
  parts: ColoredShape[],
): Promise<StlFile[]> {
  const groups = groupPartsByColor(parts);
  const filenames = stlFilenames(
    modelName,
    groups.map((group) => group.color),
  );

  const files: StlFile[] = [];

  for (let index = 0; index < groups.length; index += 1) {
    const group = groups[index];
    const buffers: ArrayBuffer[] = [];

    for (const part of group.parts) {
      const blob = part.shape.blobSTL({
        binary: true,
        tolerance: 0.02,
        angularTolerance: 0.15,
      });
      buffers.push(await blob.arrayBuffer());
    }

    const data =
      buffers.length === 1 ? buffers[0] : combineBinaryStl(buffers);

    files.push({ filename: filenames[index], data });
  }

  return files;
}
